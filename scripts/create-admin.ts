/**
 * Creates the panel admin, or re-syncs the password of an existing admin.
 *
 *   npx tsx --conditions=react-server --env-file=.env.local scripts/create-admin.ts [--promote-existing]
 *
 * Reads ADMIN_EMAIL / ADMIN_PASSWORD. When ADMIN_PASSWORD is missing in local development, a strong
 * password is generated and appended to .env.local (never in production). The password is never printed.
 *
 * Safety: an existing non-admin account (e.g. one somebody registered with the future admin address)
 * is NOT promoted unless --promote-existing is passed AND its e-mail is verified. Every promotion or
 * password change revokes all of that user's sessions, so no earlier login carries over.
 */
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import path from "node:path";
import { eq } from "drizzle-orm";
import { auth } from "@/lib/auth";
import { db } from "@/db";
import { user as userTable } from "@/db/schema";

const ENV_FILE = path.resolve(process.cwd(), ".env.local");
const DEFAULT_EMAIL = "admin@prestij.local";
const ADMIN_NAME = "PRESTİJ Yönetici";
const PROMOTE_FLAG = "--promote-existing";

function persistGeneratedCredentials(email: string, password: string, writeEmail: boolean) {
  const current = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, "utf8") : "";
  const lines = [
    "",
    "# Panel admin (generated by scripts/create-admin.ts, local development only)",
    ...(writeEmail ? [`ADMIN_EMAIL=${email}`] : []),
    `ADMIN_PASSWORD=${password}`,
  ];
  const prefix = current.length > 0 && !current.endsWith("\n") ? "\n" : "";
  appendFileSync(ENV_FILE, prefix + lines.join("\n") + "\n", "utf8");
}

async function main() {
  const email = (process.env.ADMIN_EMAIL?.trim() || DEFAULT_EMAIL).toLowerCase();
  let password = process.env.ADMIN_PASSWORD ?? "";

  if (!password) {
    if (process.env.NODE_ENV === "production") {
      throw new Error("ADMIN_PASSWORD must be set in production (no credentials are written to disk).");
    }
    password = randomBytes(18).toString("base64url"); // 24 chars, ~144 bits
    persistGeneratedCredentials(email, password, !process.env.ADMIN_EMAIL);
  }

  const ctx = await auth.$context;
  const { minPasswordLength, maxPasswordLength } = ctx.password.config;
  if (password.length < minPasswordLength || password.length > maxPasswordLength) {
    throw new Error(`ADMIN_PASSWORD must be ${minPasswordLength}-${maxPasswordLength} characters long.`);
  }

  const existing = await ctx.internalAdapter.findUserByEmail(email);

  if (!existing) {
    await auth.api.createUser({
      body: { email, password, name: ADMIN_NAME, role: "admin", data: { emailVerified: true } },
    });
    console.log(`Admin created: ${email}`);
    return;
  }

  const { user } = existing;
  const [current] = await db.select({ role: userTable.role }).from(userTable).where(eq(userTable.id, user.id)).limit(1);
  const role = current?.role ?? "customer";
  let revoke = false;

  if (role !== "admin") {
    if (!process.argv.includes(PROMOTE_FLAG)) {
      throw new Error(
        `${email} already exists as a "${role}" account. It was not promoted: it may have been ` +
          `registered by someone else. Use another ADMIN_EMAIL, or pass ${PROMOTE_FLAG} if you own this verified account.`,
      );
    }
    if (!user.emailVerified) {
      throw new Error(`${email} has not verified its e-mail address, so it cannot be promoted to admin.`);
    }
    await ctx.internalAdapter.updateUser(user.id, { role: "admin", banned: false });
    revoke = true;
  }

  // Staff accounts always count as verified (customer sign-in requires a verified e-mail since day 4).
  if (!user.emailVerified) await db.update(userTable).set({ emailVerified: true, updatedAt: new Date() }).where(eq(userTable.id, user.id));

  // ADMIN_PASSWORD is the source of truth; only touch the credential when it actually differs.
  const credential = await ctx.internalAdapter.findCredentialAccount(user.id);
  const matches = credential?.password ? await ctx.password.verify({ hash: credential.password, password }) : false;
  if (!matches) {
    const hash = await ctx.password.hash(password);
    if (credential) await ctx.internalAdapter.updatePassword(user.id, hash);
    else await ctx.internalAdapter.linkAccount({ providerId: "credential", accountId: user.id, userId: user.id, password: hash });
    revoke = true;
  }

  if (revoke) await ctx.internalAdapter.deleteUserSessions(user.id);

  const [row] = await db.select({ role: userTable.role }).from(userTable).where(eq(userTable.email, email)).limit(1);
  if (row?.role !== "admin") throw new Error(`User ${email} does not have the admin role.`);

  console.log(
    revoke ? `Admin updated: ${email} (password synced, all sessions revoked)` : `Admin ready: ${email} (no changes needed)`,
  );
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error("create-admin failed:", error instanceof Error ? error.message : error);
    process.exit(1);
  });
